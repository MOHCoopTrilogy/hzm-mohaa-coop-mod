#!/usr/bin/env python3
"""gen_lobby_briefs.py - writes coop_mod/lobbybrief.scr from each map's OWN vanilla objective text.

Run from the mod root:  python docs/tools/gen_lobby_briefs.py

For every maps/<map>.scr (+ maps/<map>/*.scr) it collects the objective strings the map registers:
    add_objectives <idx> <status> "text"   |   addobjective <idx> <status> "text"   |   exec global/obj.scr <idx> <status> "text"
where "text" may also be a level.<Var> that the map assigns a literal string to. Duplicates (the same objective is
re-registered at each status change) are dropped, order of first appearance is kept. Each text is word-wrapped to
WRAP chars and the whole panel is capped at MAXLINES lines. No new art, no invented text.
The generated label  lobbybrief.scr::briefLines <map>  fills level.coop_briefN / level.coop_briefT[1..N]  (N = 0: none).
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WRAP = 34
MAXLINES = 8
CALL = re.compile(r'(?:add_objectives|addobjective|exec\s+global/obj\.scr)\s+(\S+)\s+(\S+)\s+("([^"]*)"|level\.\w+)')
ASSIGN = re.compile(r'level\.(\w+)\s*=\s*"([^"]*)"')


def files_for(m):
    fs = [os.path.join(ROOT, "maps", m + ".scr")]
    fs += sorted(glob.glob(os.path.join(ROOT, "maps", m, "*.scr")))
    return [f for f in fs if os.path.exists(f)]


def clean(t):
    t = t.encode("ascii", "ignore").decode().replace("\\", "").strip()
    t = re.sub(r"\s+", " ", t)
    return t


def wrap(t):
    out, cur = [], ""
    for w in t.split(" "):
        if cur and len(cur) + 1 + len(w) > WRAP:
            out.append(cur)
            cur = w
        else:
            cur = (cur + " " + w).strip()
    if cur:
        out.append(cur)
    return out


def collect(m):
    code = []
    for f in files_for(m):
        for ln in open(f, encoding="latin-1"):
            if ln.strip().startswith("//"):
                continue
            code.append(ln.split("//")[0])
    assigns = {}
    for ln in code:
        for k, v in ASSIGN.findall(ln):
            assigns.setdefault(k, v)
    seen, texts = set(), []
    for ln in code:
        for idx, st, arg, lit in CALL.findall(ln):
            t = lit if arg.startswith('"') else assigns.get(arg[len("level."):], "")
            t = clean(t)
            if len(t) < 6 or t in seen or "$$" in t:
                continue
            seen.add(t)
            texts.append(t)
    return texts


def main():
    maps = sorted(set(os.path.basename(f)[:-4] for f in glob.glob(os.path.join(ROOT, "maps", "*.scr"))))
    maps = [m for m in maps if not m.startswith(("co_lobby", "briefing")) and "precache" not in m and not m.endswith("_arena")]
    blocks, n_maps = [], 0
    for m in maps:
        texts = collect(m)
        if not texts:
            continue
        blocks_t = []
        for t in texts:
            w = wrap(t)
            w[0] = "- " + w[0]
            blocks_t.append([w[0]] + ["  " + x for x in w[1:]])
        total = sum(len(b) for b in blocks_t)
        lines, shown = [], 0
        if total <= MAXLINES:
            for b in blocks_t:
                lines += b
                shown += 1
        else:
            for b in blocks_t:            # whole objectives only, one line kept for "+N more"
                if len(lines) + len(b) > MAXLINES - 1:
                    break
                lines += b
                shown += 1
            lines.append("+%d more" % (len(blocks_t) - shown))
        if not lines:
            continue
        n_maps += 1
        body = "\n".join('\t\tlevel.coop_briefT[%d] = "%s"' % (i + 1, l.replace('"', "'")) for i, l in enumerate(lines))
        blocks.append('\tif( local.m == "%s" ){\n\t\tlevel.coop_briefN = %d\n%s\n\t\tend\n\t}\n' % (m, len(lines), body))
    out = ["//=========================================================================",
           "// GENERATED by docs/tools/gen_lobby_briefs.py - do not edit by hand. [lobbyall 2026-10-19]",
           "// Lobby briefing text = each map's own vanilla objective strings (%d maps). Used by lobby.scr::lobbyBriefDraw." % n_maps,
           "//=========================================================================",
           "briefLines local.m:{", "\tlevel.coop_briefN = 0"] + [b.rstrip("\n") for b in blocks] + ["}end", ""]
    path = os.path.join(ROOT, "coop_mod", "lobbybrief.scr")
    with open(path, "wb") as f:
        f.write("\r\n".join(out).encode("ascii"))
    print("wrote", path, n_maps, "maps")


if __name__ == "__main__":
    main()
